// pack_assets <disk.adf> <out.cpp>: writes src/embedded_assets.cpp with the files the game needs as byte arrays.
#include <cstdio>
#include <string>
#include "../src/adf.hpp"
using namespace tg;
int main(int argc, char** argv) {
    if (argc < 3) { std::fprintf(stderr, "usage: pack_assets disk.adf out.cpp\n"); return 2; }
    Adf adf; std::string err;
    if (!adf.loadFile(argv[1], err)) { std::fprintf(stderr, "%s\n", err.c_str()); return 1; }
    const char* names[] = {"TANGRAM.DAT", "TANGRAM.MLU", "TITLEPIC.LO5", "THALION.LO5", "MUSIC1.IMG", "MUSIC2.IMG", "HIGHSCOREPIC.LO5", "SCORE.DTA"};
    std::FILE* f = std::fopen(argv[2], "w");
    if (!f) return 1;
    std::fprintf(f, "// Generated by tools/pack_assets - do not edit. Original game data, for personal use with your own copy of the game.\n");
    std::fprintf(f, "#include \"embedded_assets.hpp\"\n\nnamespace tg {\nnamespace {\n");
    for (int i = 0; i < 8; i++) {
        const Bytes* b = adf.file(names[i]);
        if (!b) { std::fprintf(stderr, "missing %s\n", names[i]); return 1; }
        std::fprintf(f, "const unsigned char kFile%d[%zu] = {", i, b->size());
        for (size_t k = 0; k < b->size(); k++) std::fprintf(f, "%s%u,", k % 32 ? "" : "\n", unsigned((*b)[k]));
        std::fprintf(f, "\n};\n");
    }
    std::fprintf(f, "}  // namespace\n\nvoid loadEmbeddedAssets(Adf& adf) {\n");
    for (int i = 0; i < 8; i++) std::fprintf(f, "    adf.addFile(\"%s\", Bytes(kFile%d, kFile%d + sizeof kFile%d));\n", names[i], i, i, i);
    std::fprintf(f, "}\n\n}  // namespace tg\n");
    std::fclose(f);
    return 0;
}
